// Run with Node and Playwright available; set PLAYWRIGHT_MODULE for a bundled runtime.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('fs');
const output = process.env.OUTPUT_DIR || 'data/results/browser';
const baseURL = process.env.BASE_URL || 'http://127.0.0.1:8765';
fs.mkdirSync(output,{recursive:true});
(async () => {
  const browser = await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {})});
  const page = await browser.newPage({viewport:{width:1480,height:1050},deviceScaleFactor:1});
  const errors=[];page.on('pageerror',e=>errors.push(String(e)));
  await page.goto(baseURL,{waitUntil:'networkidle'});
  await page.locator('.event-card').first().waitFor();
  await page.locator('.event-card').first().click();
  await page.locator('#detail:not(.hidden)').waitFor();
  await page.waitForFunction(()=>document.querySelector('#player').readyState>=1);
  const duration=await page.locator('#player').evaluate(v=>v.duration);
  if(!Number.isFinite(duration)||duration<=0)throw Error('Video metadata missing');
  await page.locator('#evidence button').nth(1).click();
  const sought=await page.locator('#player').evaluate(v=>v.currentTime);
  if(sought<=0)throw Error('Evidence seeking failed');
  await page.locator('#search').fill('quuxunicorn');
  await page.waitForFunction(()=>document.querySelectorAll('.event-card').length===0);
  await page.locator('#search').fill('');
  await page.locator('.event-card').first().waitFor();
  await page.locator('.event-card').first().click();
  await page.locator('#exportButton').click();
  await page.locator('#includePending').check();
  const submitted=page.waitForResponse(r=>r.url().endsWith('/api/exports')&&r.request().method()==='POST');
  await page.locator('#startExport').click();
  const job=await (await submitted).json();
  let completedJob;
  const deadline=Date.now()+60000;
  while(Date.now()<deadline){
    const response=await page.request.get(baseURL+'/api/jobs/'+job.id);
    const current=await response.json();
    if(current.status==='failed')throw Error(current.error);
    if(current.status==='completed'&&current.result){completedJob=current;break;}
    await page.waitForTimeout(500);
  }
  if(!completedJob)throw Error('New export did not complete within 60 seconds: '+job.id);
  const jobResult=completedJob.result;
  const downloadLink=page.locator(`#jobsPanel a[href="/api/exports/${jobResult.id}"]`);
  await downloadLink.waitFor({timeout:60000});
  const href=await downloadLink.getAttribute('href');
  const response=await page.request.get(new URL(href,page.url()).href);
  if(!response.ok())throw Error('Export download failed');
  const zip=await response.body();
  if(zip.subarray(0,2).toString()!=='PK')throw Error('Export is not ZIP');
  await page.waitForFunction(()=>{const p=document.querySelector('#player');return p.readyState>=2&&!p.seeking});
  await page.locator('#toast').waitFor({state:'hidden',timeout:10000});
  if(process.env.SCREENSHOTS)await page.screenshot({path:output+'/desktop.png',fullPage:true});
  const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
  await mobile.goto(baseURL,{waitUntil:'networkidle'});
  await mobile.locator('.event-card').first().waitFor();
  const options=await mobile.locator('#videoFilter option').count();
  if(options<2)throw Error('No mobile video selection');
  await mobile.locator('#videoFilter').selectOption({index:1});
  await mobile.locator('.event-card').first().click();
  if(process.env.SCREENSHOTS)await mobile.screenshot({path:output+'/mobile.png'});
  await mobile.locator('#detail').scrollIntoViewIfNeeded();
  if(process.env.SCREENSHOTS)await mobile.screenshot({path:output+'/mobile-review.png'});
  const overflow=await mobile.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
  if(overflow)throw Error('Mobile horizontal overflow');
  const clipped=await mobile.evaluate(()=>[...document.querySelectorAll('.detail,.evidence,.evidence button,.boundary-fields,#start,#end,#description')].some(el=>{const r=el.getBoundingClientRect();return r.right>innerWidth+1||r.left<0}));
  if(clipped)throw Error('Mobile review content is clipped');
  if(errors.length)throw Error(errors.join('\n'));
  fs.writeFileSync(output+'/result.json',JSON.stringify({passed:true,video_duration:duration,evidence_seek:sought,export_bytes:zip.length,export_url:href,console_errors:errors,mobile_overflow:overflow,mobile_review_clipped:clipped,checks:['page loads','real video metadata','evidence seek','empty search','pending export ZIP','mobile video selection','mobile review layout']},null,2));
  console.log('Browser checks passed. Results: '+output+'/result.json');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
